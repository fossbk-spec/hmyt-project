#IMPORT THƯ VIỆN
import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

pd.set_option("display.max_columns", 100)
pd.set_option("display.width", 160)

OUTPUT_DIR = "/content/eda_outputs"
os.makedirs(OUTPUT_DIR, exist_ok=True)

print("Output folder:", OUTPUT_DIR)

#UPLOAD DATASET
import os
import glob

# Tìm file hf_model_dataset_final đã upload trong Colab
files_found = glob.glob("/content/hf_model_dataset_final*.gz")

if len(files_found) == 0:
    raise FileNotFoundError(
        "Không tìm thấy hf_model_dataset_final*.gz trong /content"
    )

DATA_FILE = files_found[-1]

print("Đang dùng file:", DATA_FILE)
print("Kích thước:", os.path.getsize(DATA_FILE), "bytes")

#ĐỌC DỮ LIỆU
df = pd.read_csv(
    DATA_FILE,
    parse_dates=["admittime", "dischtime"]
)

print("Shape:", df.shape)
print("Số bệnh nhân:", df["subject_id"].nunique())
print("Số admissions:", len(df))
print("Số cột:", df.shape[1])

display(df.head())

"""# **EDA 1 — Tổng quan cohort**

**Cell 2 — Thống kê cohort**
"""

n_patients = df["subject_id"].nunique()
n_admissions = len(df)

n_readmit = int((df["readmit_30d"] == 1).sum())
n_no_readmit = int((df["readmit_30d"] == 0).sum())

readmit_rate = 100 * n_readmit / n_admissions

median_age = df["age"].median()

summary = pd.DataFrame({
    "Thông tin": [
        "HF patients",
        "HF admissions",
        "Readmission ≤30 ngày",
        "Non-readmission",
        "Readmission rate (%)",
        "Median age"
    ],
    "Kết quả": [
        n_patients,
        n_admissions,
        n_readmit,
        n_no_readmit,
        round(readmit_rate, 2),
        median_age
    ]
})

display(summary)

"""**Cell 3 — Phân bố giới tính**"""

patient_demo = (
    df.sort_values("admittime")
      .drop_duplicates("subject_id")
)

gender_count = patient_demo["gender"].value_counts(dropna=False)

gender_percent = (
    100 * gender_count / gender_count.sum()
).round(2)

gender_summary = pd.DataFrame({
    "Patients": gender_count,
    "Percent": gender_percent
})

display(gender_summary)

"""**Cell 4 — Biểu đồ phân bố Readmission / Non-readmission**"""

counts = (
    df["readmit_30d"]
    .value_counts()
    .reindex([0, 1])
)

labels = [
    "No readmission",
    "Readmission ≤30d"
]

fig, ax = plt.subplots(figsize=(8, 5.2))

bars = ax.bar(
    labels,
    counts.values
)

ax.set_ylabel("Admissions")
ax.set_xlabel("Outcome")

for bar, value in zip(bars, counts.values):
    ax.text(
        bar.get_x() + bar.get_width()/2,
        bar.get_height() + counts.max()*0.012,
        f"{int(value):,}",
        ha="center"
    )

ax.set_ylim(
    0,
    counts.max()*1.1
)

plt.tight_layout()

plt.savefig(
    f"{OUTPUT_DIR}/01_class_distribution.png",
    dpi=220,
    bbox_inches="tight"
)

plt.show()

"""# **EDA 2 — So sánh hai nhóm**

**Cell 5 — So sánh các đặc trưng**
"""

compare_features = [
    "age",
    "los_days",
    "prior_admissions",
    "prior_hf_admissions",
    "prior_admissions_1y",
    "n_diagnoses",
    "n_procedures",
    "n_unique_drugs",
    "creatinine_last",
    "bun_last",
    "hemoglobin_last"
]

compare_features = [
    c for c in compare_features
    if c in df.columns
]

group_compare = (
    df.groupby("readmit_30d")[compare_features]
      .median(numeric_only=True)
      .T
)

group_compare.columns = [
    "No readmission",
    "Readmission ≤30d"
]

group_compare["Difference"] = (
    group_compare["Readmission ≤30d"]
    - group_compare["No readmission"]
)

display(
    group_compare.round(2)
)

"""**Cell 6 — Boxplot Prior Admissions**"""

no_readmit = df.loc[
    df["readmit_30d"] == 0,
    "prior_admissions"
].dropna()

readmit = df.loc[
    df["readmit_30d"] == 1,
    "prior_admissions"
].dropna()

fig, ax = plt.subplots(figsize=(8, 5.2))

ax.boxplot(
    [
        no_readmit,
        readmit
    ],
    tick_labels=[
        "No readmission",
        "Readmission ≤30d"
    ],
    showfliers=False
)

ax.set_ylabel(
    "Number of prior admissions"
)

plt.tight_layout()

plt.savefig(
    f"{OUTPUT_DIR}/02_prior_admissions_boxplot.png",
    dpi=220,
    bbox_inches="tight"
)

plt.show()

"""**Cell 7 — Lấy median Prior Admissions chính xác**"""

prior_summary = (
    df.groupby("readmit_30d")
      ["prior_admissions"]
      .agg([
          "count",
          "median",
          "mean",
          "std"
      ])
)

prior_summary.index = [
    "No readmission",
    "Readmission ≤30d"
]

display(
    prior_summary.round(2)
)

"""# **EDA 3 — Missing Data**
**Cell 8 — Tính tỷ lệ missing**
"""

missingness = (
    df.isna()
      .mean()
      .mul(100)
      .sort_values(
          ascending=False
      )
      .rename("missing_pct")
      .reset_index()
      .rename(
          columns={
              "index": "feature"
          }
      )
)

display(
    missingness.head(25)
)

"""**Cell 9 — Tìm biến và vẽ biểu đồ Missing Data**"""

# TÌM BIẾN MISSING
DROP_THRESHOLD = 60

drop_candidates = missingness[
    missingness["missing_pct"]
    > DROP_THRESHOLD
]

print("Các biến có missing > 60%:")

display(
    drop_candidates
)

# VẼ BIỂU ĐỒ MISSING DATA
top_missing = (
    missingness
    .head(8)
    .copy()
)

fig, ax = plt.subplots(
    figsize=(10, 5.5)
)

bars = ax.bar(
    top_missing["feature"],
    top_missing["missing_pct"]
)

ax.set_ylabel(
    "Missing data (%)"
)

ax.tick_params(
    axis="x",
    rotation=35
)

max_y = max(
    top_missing["missing_pct"].max(),
    1
)

for bar, value in zip(
    bars,
    top_missing["missing_pct"]
):
    ax.text(
        bar.get_x()
        + bar.get_width()/2,
        bar.get_height()
        + max_y*0.012,
        f"{value:.1f}%",
        ha="center"
    )

ax.set_ylim(
    0,
    max_y*1.12
)

plt.tight_layout()

plt.savefig(
    f"{OUTPUT_DIR}/03_missingness.png",
    dpi=220,
    bbox_inches="tight"
)

plt.show()

"""# **EDA 4 — Correlation**
**Cell 13 — Chọn các biến để tính correlation**
"""

corr_features = [
    "age",
    "los_days",
    "prior_admissions",
    "prior_hf_admissions",
    "prior_admissions_30d",
    "prior_admissions_90d",
    "prior_admissions_1y",

    "n_diagnoses",
    "n_procedures",
    "n_unique_drugs",

    "creatinine_last",
    "bun_last",
    "sodium_last",
    "potassium_last",
    "hemoglobin_last",

    "readmit_30d"
]

corr_features = [
    c for c in corr_features
    if c in df.columns
]

corr = (
    df[corr_features]
    .corr(
        method="pearson"
    )
)

display(
    corr.round(2)
)

"""**Cell 12 — Vẽ heatmap correlation**"""

fig, ax = plt.subplots(
    figsize=(12, 10)
)

im = ax.imshow(
    corr.values,
    vmin=-1,
    vmax=1,
    aspect="auto"
)

ax.set_xticks(
    np.arange(
        len(corr_features)
    )
)

ax.set_yticks(
    np.arange(
        len(corr_features)
    )
)

ax.set_xticklabels(
    corr_features,
    rotation=55,
    ha="right",
    fontsize=8
)

ax.set_yticklabels(
    corr_features,
    fontsize=8
)

for i in range(len(corr_features)):
    for j in range(len(corr_features)):
        ax.text(
            j,
            i,
            f"{corr.iloc[i,j]:.2f}",
            ha="center",
            va="center",
            fontsize=6
        )

cbar = fig.colorbar(
    im,
    ax=ax
)

cbar.set_label(
    "Correlation coefficient"
)

plt.tight_layout()

plt.savefig(
    f"{OUTPUT_DIR}/04_correlation_heatmap.png",
    dpi=220,
    bbox_inches="tight"
)

plt.show()

"""# **EDA 5 — Kiểm tra chất lượng dữ liệu**
**Cell 14 — Duplicate / label / tuổi / LOS**
"""

quality_check = pd.DataFrame({
    "Check": [
        "Duplicate subject_id + hadm_id",
        "Missing subject_id",
        "Missing hadm_id",
        "Invalid readmit label",
        "Age < 18",
        "LOS < 1 day"
    ],

    "Count": [
        df.duplicated(
            ["subject_id", "hadm_id"]
        ).sum(),

        df["subject_id"]
        .isna()
        .sum(),

        df["hadm_id"]
        .isna()
        .sum(),

        (
            ~df["readmit_30d"]
            .isin([0,1])
        ).sum(),

        (
            df["age"] < 18
        ).sum(),

        (
            df["los_days"] < 1
        ).sum()
    ]
})

display(
    quality_check
)